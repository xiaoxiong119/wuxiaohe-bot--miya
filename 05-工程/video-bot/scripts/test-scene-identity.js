const assert = require('node:assert/strict');
const ID = require('../src/task-identity'), names = require('../src/epname'), comments = require('../src/scene-comments');
assert.deepEqual(ID.parse('《逆天萌兽3》64-2-修改版.mp4'), {episode:64,scene:2,whole:false,label:'64-2'});
assert.equal(ID.parse('《逆天萌兽3》64-1.mp4').episode,64);
assert.equal(ID.parse('64-整集.mp4').whole,true);
assert.equal(ID.parse('第64集第2场.mp4').scene,2);
assert.equal(ID.parse('随便2026.mp4'),null);
assert.equal(names.stripRev('64-2-修改版.mp4'),'64-2.mp4');
assert.notEqual(names.subjectKey('64-1.mp4'),names.subjectKey('64-2.mp4'));
assert.notEqual(names.subjectKey('6-41.mp4'),names.subjectKey('64-1.mp4'));
assert.equal(names.subjectKey('64-2-修改版.mp4'),names.subjectKey('64-2.mov'));
const rows=[{episode:64,scene:1,recordId:'a'},{episode:64,scene:2,recordId:'b'}];
assert.equal(ID.select(rows,ID.parse('64-2.mp4')).recordId,'b');
assert.throws(()=>ID.select(rows,ID.parse('64.mp4')),/明确/);
assert.throws(()=>ID.select([...rows,rows[0]],ID.parse('64-1.mp4')),/不唯一/);
const a={episode:64,scene:1,file:'64-1.mp4',version:'2',timeline:'00:12',content:'声音太小'};
const b={...a,scene:2,file:'64-2.mp4'};
assert.notEqual(comments.key(a),comments.key(b));
assert.notEqual(comments.key(a),comments.key({...a,version:'3'}));
assert.equal(comments.key({...comments.decode(comments.content(a)),timeline:a.timeline}),comments.key(a));
assert.throws(()=>comments.validate([{...a,scene:null}],{sceneMode:true}),/无法定位/);
assert.equal(comments.validate([{...a,scene:null}],{sceneMode:true,wholeEpisode:true}).length,1);
console.log('PASS: 场次文件名、项目数字排除、独立版本匹配、歧义拒绝、跨场批注去重及版本隔离');
